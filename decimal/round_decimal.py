from decimal import Decimal, ROUND_HALF_UP, ROUND_CEILING, ROUND_DOWN, ROUND_HALF_DOWN, ROUND_FLOOR
# To round numbers with Decimal, use the .quantize() method.

# Target format: '0.01' means exactly 2 decimal places. always write '0.01' not other number
target = Decimal('0.01')

num1 = Decimal('10.245')
num2 = Decimal('10.244')
num3 = Decimal('10.225')
num4 = Decimal('10.226')
num5 = Decimal('10.123')
num6 = Decimal('-10.127')
num7 = Decimal('-10.125')
num8 = Decimal('-10.124')
print(type(num1))


print("***** print without round start *******")
print(num1)
print(num2)
print(num3)
print(num4)
print(num5)
print(num6)
print(num7)
print(num8)


print("***** ROUND_HALF_UP round start *******")
# 0.5 rounds up to the next number by ROUND_HALF_UP.
a = num1.quantize(target, rounding=ROUND_HALF_UP)
b = num2.quantize(target, rounding=ROUND_HALF_UP)
c = num3.quantize(target, rounding=ROUND_HALF_UP)
d = num4.quantize(target, rounding=ROUND_HALF_UP)
e = num5.quantize(target, rounding=ROUND_HALF_UP)
f = num6.quantize(target, rounding=ROUND_HALF_UP)
g = num7.quantize(target, rounding=ROUND_HALF_UP)
h = num8.quantize(target, rounding=ROUND_HALF_UP)
print(a)
print(b)
print(c)
print(d)
print(e)
print(f)
print(g)
print(h)


print("***** ROUND_HALF_DOWN round start *******")
# If the last digit is 5, it rounds down. If it is 6 or higher, it still rounds up.
a = num1.quantize(target, rounding=ROUND_HALF_DOWN)
b = num2.quantize(target, rounding=ROUND_HALF_DOWN)
c = num3.quantize(target, rounding=ROUND_HALF_DOWN)
d = num4.quantize(target, rounding=ROUND_HALF_DOWN)
e = num5.quantize(target, rounding=ROUND_HALF_DOWN)
f = num6.quantize(target, rounding=ROUND_HALF_DOWN)
g = num7.quantize(target, rounding=ROUND_HALF_DOWN)
h = num8.quantize(target, rounding=ROUND_HALF_DOWN)
print(a)
print(b)
print(c)
print(d)
print(e)
print(f)
print(g)
print(h)

print("***** ROUND_CEILING round start *******")
# This moves the number toward positive infinity (great for calculating taxes or fees where you cannot shortchange) by ROUND_CEILING
a = num1.quantize(target, rounding=ROUND_CEILING)
b = num2.quantize(target, rounding=ROUND_CEILING)
c = num3.quantize(target, rounding=ROUND_CEILING)
d = num4.quantize(target, rounding=ROUND_CEILING)
e = num5.quantize(target, rounding=ROUND_CEILING)
f = num6.quantize(target, rounding=ROUND_CEILING)
g = num7.quantize(target, rounding=ROUND_CEILING)
h = num8.quantize(target, rounding=ROUND_CEILING)

print(a)
print(b)
print(c)
print(d)
print(e)
print(f)
print(g)
print(h)

print("***** ROUND_DOWN round start *******")
# Always Chop Off Extra Digits by ROUND_DOWN
a = num1.quantize(target, rounding=ROUND_DOWN)
b = num2.quantize(target, rounding=ROUND_DOWN)
c = num3.quantize(target, rounding=ROUND_DOWN)
d = num4.quantize(target, rounding=ROUND_DOWN)
e = num5.quantize(target, rounding=ROUND_DOWN)
f = num6.quantize(target, rounding=ROUND_DOWN)
g = num7.quantize(target, rounding=ROUND_DOWN)
h = num8.quantize(target, rounding=ROUND_DOWN)
print(a)
print(b)
print(c)
print(d)
print(e)
print(f)
print(g)
print(h)

print("***** ROUND_FLOOR round start *******")
# ROUND_FLOOR behaves differently depending on whether the number is positive or negative.
# For positive numbers, it behaves exactly like ROUND_DOWN by chopping off the extra digits.
# For negative numbers, ROUND_FLOOR makes the number smaller (further below zero).
a = num1.quantize(target, rounding=ROUND_FLOOR)
b = num2.quantize(target, rounding=ROUND_FLOOR)
c = num3.quantize(target, rounding=ROUND_FLOOR)
d = num4.quantize(target, rounding=ROUND_FLOOR)
e = num5.quantize(target, rounding=ROUND_FLOOR)
f = num6.quantize(target, rounding=ROUND_FLOOR)
g = num7.quantize(target, rounding=ROUND_FLOOR)
h = num8.quantize(target, rounding=ROUND_FLOOR)
print(a)
print(b)
print(c)
print(d)
print(e)
print(f)
print(g)
print(h)